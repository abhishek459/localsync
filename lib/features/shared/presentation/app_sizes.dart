/// A central place for all sizing, spacing, and layout constants.
///
/// This system is based on a 4.0 grid.
/// `p1 = 4.0`, `p2 = 8.0`, `p3 = 12.0`, etc.
abstract final class AppSizes {
  static const double p1 = 4.0;

  static const double p2 = 8.0;

  static const double p3 = 12.0;

  static const double p4 = 16.0;

  static const double p5 = 20.0;

  static const double p6 = 24.0;

  static const double p8 = 32.0;

  static const double p12 = 48.0;

  // --- Border Radius ---
  /// 12.0 (p3)
  static const double borderRadius = p3;

  // --- Layout Constraints ---
  /// 500.0
  static const double layoutConstraintSmall = 500.0;

  /// 600.0
  static const double layoutConstraintMedium = 600.0;

  // --- Dialog Sizes ---
  /// 800.0
  static const double dialogWidthMedium = 800.0;

  /// 550.0
  static const double dialogHeightMedium = 550.0;
}
